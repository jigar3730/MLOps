"""Null baselines and uncertainty for strategy backtests.

A backtest's average R or forward return is only meaningful relative to what
the same universe would have delivered *without* the signal. This module
provides the comparisons used as promotion gates:

* **Random-entry null (R)** – same level logic and exit rules applied at
  random bars of the same tickers (generated by the strategy's backtester).
* **Unconditional forward return** – mean forward return of every eligible bar
  of the same ticker (what "buying any week" earned).
* **Benchmark forward return** – QQQ over the same signal dates.

Uncertainty uses a ticker-clustered bootstrap: signals on the same ticker are
correlated, so tickers (not trades) are resampled.
"""
from __future__ import annotations

from typing import Callable, Iterable, Optional

import numpy as np
import pandas as pd

DEFAULT_HORIZONS = (2, 5, 13)


def forward_returns(close: pd.Series, horizons: Iterable[int] = DEFAULT_HORIZONS) -> pd.DataFrame:
    """Forward simple returns ``close[t+h] / close[t] - 1`` for each horizon (NaN past the end)."""
    close = close.astype(float)
    return pd.DataFrame({h: close.shift(-h) / close - 1.0 for h in horizons}, index=close.index)


def cluster_bootstrap_mean(
    values: np.ndarray,
    clusters: np.ndarray,
    n_boot: int = 2000,
    seed: int = 7,
    alpha: float = 0.05,
) -> dict:
    """Mean of *values* with a cluster-resampled (1-alpha) CI.

    Each bootstrap draw resamples clusters with replacement and recomputes the
    pooled mean over all their observations.
    """
    values = np.asarray(values, dtype=float)
    clusters = np.asarray(clusters)
    ok = np.isfinite(values)
    values, clusters = values[ok], clusters[ok]
    if len(values) == 0:
        return {"mean": np.nan, "lo": np.nan, "hi": np.nan, "n": 0, "clusters": 0}

    codes, uniq = pd.factorize(clusters)
    k = len(uniq)
    sums = np.bincount(codes, weights=values, minlength=k)
    counts = np.bincount(codes, minlength=k).astype(float)
    rng = np.random.default_rng(seed)
    draws = rng.integers(0, k, size=(n_boot, k))
    boot = sums[draws].sum(axis=1) / counts[draws].sum(axis=1)
    lo, hi = np.quantile(boot, [alpha / 2, 1 - alpha / 2])
    return {"mean": float(values.mean()), "lo": float(lo), "hi": float(hi),
            "n": int(len(values)), "clusters": int(k)}


def cluster_bootstrap_diff(
    a: np.ndarray, a_clusters: np.ndarray,
    b: np.ndarray, b_clusters: np.ndarray,
    n_boot: int = 2000, seed: int = 7, alpha: float = 0.05,
) -> dict:
    """Difference of pooled means (a − b) with a CI from resampling the shared cluster set.

    The same resampled tickers are used for both samples so ticker-level
    effects (e.g. a strong-trending name) cancel instead of inflating variance.
    """
    a = np.asarray(a, dtype=float); a_clusters = np.asarray(a_clusters)
    b = np.asarray(b, dtype=float); b_clusters = np.asarray(b_clusters)
    ka, kb = np.isfinite(a), np.isfinite(b)
    a, a_clusters, b, b_clusters = a[ka], a_clusters[ka], b[kb], b_clusters[kb]
    shared = np.intersect1d(np.unique(a_clusters), np.unique(b_clusters))
    if len(shared) == 0:
        return {"diff": np.nan, "lo": np.nan, "hi": np.nan, "a_mean": np.nan, "b_mean": np.nan,
                "n_a": 0, "n_b": 0, "clusters": 0}
    ma, mb = np.isin(a_clusters, shared), np.isin(b_clusters, shared)
    a, a_clusters, b, b_clusters = a[ma], a_clusters[ma], b[mb], b_clusters[mb]

    idx = {c: i for i, c in enumerate(shared)}
    ca = np.array([idx[c] for c in a_clusters]); cb = np.array([idx[c] for c in b_clusters])
    k = len(shared)
    sa, na = np.bincount(ca, weights=a, minlength=k), np.bincount(ca, minlength=k).astype(float)
    sb, nb = np.bincount(cb, weights=b, minlength=k), np.bincount(cb, minlength=k).astype(float)
    rng = np.random.default_rng(seed)
    draws = rng.integers(0, k, size=(n_boot, k))
    boot = sa[draws].sum(1) / na[draws].sum(1) - sb[draws].sum(1) / nb[draws].sum(1)
    lo, hi = np.quantile(boot, [alpha / 2, 1 - alpha / 2])
    return {"diff": float(a.mean() - b.mean()), "lo": float(lo), "hi": float(hi),
            "a_mean": float(a.mean()), "b_mean": float(b.mean()),
            "n_a": int(len(a)), "n_b": int(len(b)), "clusters": int(k)}


def forward_return_baselines(
    trades: pd.DataFrame,
    load_close: Callable[[str], Optional[pd.Series]],
    benchmark_close: Optional[pd.Series],
    horizons: Iterable[int] = DEFAULT_HORIZONS,
    start_bar: int = 0,
    n_boot: int = 2000,
) -> pd.DataFrame:
    """Signal forward returns vs same-ticker unconditional and vs benchmark.

    *trades* needs ``Symbol``, ``Signal Date`` and ``Forward_Return_{h}w``
    columns. *load_close(symbol)* returns a Date-indexed close series.
    Unconditional returns use every bar from ``start_bar`` onward that falls
    within the backtest's signal date span.
    """
    horizons = tuple(horizons)
    t = trades.copy()
    t["Signal Date"] = pd.to_datetime(t["Signal Date"])
    lo_date, hi_date = t["Signal Date"].min(), t["Signal Date"].max()

    uncond_vals = {h: [] for h in horizons}
    uncond_clusters: list[str] = []
    for sym in t["Symbol"].unique():
        close = load_close(sym)
        if close is None or len(close) <= start_bar:
            continue
        fr = forward_returns(close, horizons).iloc[start_bar:]
        fr = fr[(fr.index >= lo_date) & (fr.index <= hi_date)]
        for h in horizons:
            uncond_vals[h].append(fr[h].to_numpy())
        uncond_clusters.extend([sym] * len(fr))
    uncond_clusters = np.array(uncond_clusters)

    bench_fr = forward_returns(benchmark_close, horizons) if benchmark_close is not None else None
    rows = []
    for h in horizons:
        col = f"Forward_Return_{h}w"
        if col not in t.columns:
            continue
        sig = t[col].astype(float).to_numpy()
        sym = t["Symbol"].to_numpy()
        uncond = np.concatenate(uncond_vals[h]) if uncond_vals[h] else np.array([])
        vs_rand = cluster_bootstrap_diff(sig, sym, uncond, uncond_clusters, n_boot=n_boot)
        row = {"horizon_bars": h, "signal_mean": vs_rand["a_mean"], "random_mean": vs_rand["b_mean"],
               "excess_vs_random": vs_rand["diff"], "excess_vs_random_lo": vs_rand["lo"],
               "excess_vs_random_hi": vs_rand["hi"], "n_signals": vs_rand["n_a"],
               "tickers": vs_rand["clusters"]}
        if bench_fr is not None:
            b = bench_fr[h].reindex(t["Signal Date"]).to_numpy()
            ex = cluster_bootstrap_mean(sig - b, sym, n_boot=n_boot)
            row.update({"benchmark_mean": float(np.nanmean(b)), "excess_vs_benchmark": ex["mean"],
                        "excess_vs_benchmark_lo": ex["lo"], "excess_vs_benchmark_hi": ex["hi"]})
        rows.append(row)
    return pd.DataFrame(rows)


def r_per_signal(df: pd.DataFrame) -> np.ndarray:
    """Expectancy per signal: filled trades contribute their R, unfilled signals 0R.

    Using per-signal (not per-fill) expectancy makes strategies with different
    fill rates comparable: an order that never fills earned nothing.
    """
    r = pd.to_numeric(df["R Multiple"], errors="coerce")
    return np.where(df["Outcome"].eq("no_fill"), 0.0, r.to_numpy(dtype=float))


def promotion_gate(r_vs_random: dict, fwd: pd.DataFrame, primary_horizon: int) -> dict:
    """PASS only if the strategy beats its random-entry null with 95% confidence.

    Requires both: R-per-signal CI vs random entry above 0, and the forward
    return excess vs random entry at *primary_horizon* with CI above 0.
    """
    reasons = []
    ok_r = bool(np.isfinite(r_vs_random.get("lo", np.nan)) and r_vs_random["lo"] > 0)
    if not ok_r:
        reasons.append(f"R/signal vs random-entry CI lower bound {r_vs_random.get('lo', np.nan):+.3f} <= 0")
    prim = fwd[fwd["horizon_bars"] == primary_horizon]
    ok_f = bool(len(prim) and prim["excess_vs_random_lo"].iloc[0] > 0)
    if not ok_f:
        lo = prim["excess_vs_random_lo"].iloc[0] if len(prim) else np.nan
        reasons.append(f"{primary_horizon}-bar forward excess vs random CI lower bound {lo:+.4f} <= 0")
    return {"pass": ok_r and ok_f, "reasons": reasons}
